package org.example;

public class producao {

        public static void main(String[] args) {

            // Inicia o contador de peças
            int peca = 1;

            // Verifica se a peça é menor ou igual a 20
            while (peca <= 20) {

                // Exibe a mensagem de peça produzida
                System.out.println("Peça Produzida");

                // Incrementa o contador
                peca++;
            }
        }
}
