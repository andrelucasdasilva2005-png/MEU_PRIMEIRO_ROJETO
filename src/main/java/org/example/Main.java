public class Main {
    public static void main(String[] args) {
        // 1. Declaração de duas variáveis inteiras com valores diferentes
        int numero1 = 15;
        int numero2 = 8;

        // Exibe os valores escolhidos
        System.out.println("Número 1: " + numero1);
        System.out.println("Número 2: " + numero2);
        System.out.println("-------------------------");

        // 2. Comparações e exibição dos resultados
        System.out.println("numero1 > numero2  (Maior que): " + (numero1 > numero2));
        System.out.println("numero1 < numero2  (Menor que): " + (numero1 < numero2));
        System.out.println("numero1 >= numero2 (Maior ou igual): " + (numero1 >= numero2));
        System.out.println("numero1 <= numero2 (Menor ou igual): " + (numero1 <= numero2));
        System.out.println("numero1 == numero2 (Igual a): " + (numero1 == numero2));
        System.out.println("numero1 != numero2 (Diferente de): " + (numero1 != numero2));
    }
            }